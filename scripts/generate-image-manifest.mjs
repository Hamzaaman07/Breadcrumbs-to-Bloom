// Scans /public/images and writes lib/image-manifest.ts.
//
// Why this exists: BakeryImage used to check the filesystem at render time
// with node:fs. That works on a Node server but NOT on Cloudflare Workers,
// Vercel Edge, or any other filesystem-less runtime — where it would fail
// silently and render a placeholder in place of every real photo.
//
// Resolving the list at build time instead makes the lookup a plain object
// read, so it behaves identically on every runtime. The "drop a file in and
// it just works" workflow is unchanged: this regenerates on every build.

import { readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = join(root, "public", "images");
const outFile = join(root, "lib", "image-manifest.ts");

const ALLOWED = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

const entries = existsSync(imagesDir)
  ? readdirSync(imagesDir)
      .filter((f) => ALLOWED.has(extname(f).toLowerCase()))
      .sort()
  : [];

// slot name === filename without extension
const manifest = {};
for (const file of entries) {
  manifest[basename(file, extname(file))] = `/images/${file}`;
}

const body = `// GENERATED FILE — do not edit by hand.
// Regenerated by scripts/generate-image-manifest.mjs on every build.
// To add a photo: drop it in /public/images/<slot>.jpg and rebuild.

export const imageManifest: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(
  `[image-manifest] ${entries.length} image${entries.length === 1 ? "" : "s"} indexed`
);
